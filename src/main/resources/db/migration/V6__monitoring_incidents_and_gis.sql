-- 3. Incident Tickets (Sự cố hiện trường SC-YYYYMMDD-XXXX)
CREATE TABLE incident_tickets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_code VARCHAR(50) NOT NULL UNIQUE,
    location_id BIGINT REFERENCES wifi_locations(id),
    device_id BIGINT REFERENCES network_devices(id),
    incident_type VARCHAR(50) NOT NULL, -- POWER_OUTAGE, FIBER_CUT, HARDWARE_FAULT, SYSTEM_DEGRADATION
    severity VARCHAR(20) NOT NULL DEFAULT 'MAJOR', -- CRITICAL, MAJOR, MINOR
    status VARCHAR(30) NOT NULL DEFAULT 'NEW', -- NEW, ASSIGNED, IN_PROGRESS, RESOLVED, CLOSED
    title VARCHAR(255) NOT NULL,
    description TEXT,
    assigned_to VARCHAR(100), -- Kỹ thuật viên nhà mạng hoặc đội cơ động
    sla_deadline TIMESTAMP WITH TIME ZONE NOT NULL,
    resolved_at TIMESTAMP WITH TIME ZONE,
    resolution_notes TEXT,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_incident_tickets_code ON incident_tickets(ticket_code);
CREATE INDEX idx_incident_tickets_status ON incident_tickets(status);
CREATE INDEX idx_incident_tickets_location ON incident_tickets(location_id);

-- 4. Incident Updates & Audit Trail
CREATE TABLE incident_updates (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id BIGINT NOT NULL REFERENCES incident_tickets(id),
    actor VARCHAR(100) NOT NULL,
    action VARCHAR(50) NOT NULL, -- COMMENT, STATUS_CHANGE, ASSIGN, RESOLVE
    notes TEXT,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_incident_updates_ticket ON incident_updates(ticket_id);

