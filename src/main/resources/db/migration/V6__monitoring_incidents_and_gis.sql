-- 1. Device Telemetry Metrics (Heartbeat, CPU, RAM, Bandwidth, Latency)
CREATE TABLE device_telemetry_metrics (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device_id BIGINT REFERENCES network_devices(id),
    location_id BIGINT REFERENCES wifi_locations(id),
    cpu_usage_percent DOUBLE PRECISION,
    memory_usage_percent DOUBLE PRECISION,
    active_client_count INT DEFAULT 0,
    rx_bytes_sec BIGINT DEFAULT 0,
    tx_bytes_sec BIGINT DEFAULT 0,
    ping_latency_ms INT DEFAULT 0,
    packet_loss_percent DOUBLE PRECISION DEFAULT 0.0,
    recorded_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_telemetry_device ON device_telemetry_metrics(device_id, recorded_at);
CREATE INDEX idx_telemetry_location ON device_telemetry_metrics(location_id, recorded_at);

-- 2. Alert Rules & Notification Matrix
CREATE TABLE alert_rules (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rule_name VARCHAR(100) NOT NULL,
    metric_type VARCHAR(50) NOT NULL, -- OFFLINE, HIGH_CPU, HIGH_PACKET_LOSS, BANDWIDTH_EXHAUSTION
    threshold_value DOUBLE PRECISION NOT NULL,
    severity VARCHAR(20) NOT NULL DEFAULT 'MAJOR', -- CRITICAL, MAJOR, MINOR, WARNING
    notification_channel VARCHAR(50) NOT NULL DEFAULT 'TELEGRAM', -- TELEGRAM, WEBHOOK, EMAIL, SMS
    target_channel_id VARCHAR(255),
    is_enabled BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

