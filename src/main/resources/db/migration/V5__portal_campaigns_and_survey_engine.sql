-- ==============================================================================
-- V5: Portal Templates, Media & Policy Campaigns, Smart Survey Engine & OTP
-- Compatible with PostgreSQL 12+ and H2 (PostgreSQL Mode)
-- ==============================================================================

-- 1. Portal Templates
CREATE TABLE portal_templates (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    template_type VARCHAR(50) NOT NULL DEFAULT 'DEFAULT', -- DEFAULT, CULTURAL, BANNER_SURVEY, VIDEO_AD
    theme_color VARCHAR(50) DEFAULT '#0284c7',
    background_color VARCHAR(50) DEFAULT '#f8fafc',
    logo_url VARCHAR(500),
    banner_url VARCHAR(500),
    title VARCHAR(255) NOT NULL,
    welcome_text TEXT,
    button_text VARCHAR(100) DEFAULT 'Kết nối Wi-Fi Miễn Phí',
    terms_text TEXT,
    layout_config TEXT,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);

-- 2. Policy & Media Campaigns (2-step Approval Workflow: DRAFT -> PENDING_APPROVAL -> APPROVED / REJECTED)
CREATE TABLE campaigns (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(255) NOT NULL,
    description TEXT,
    banner_url VARCHAR(500),
    video_url VARCHAR(500),
    action_url VARCHAR(500),
    target_admin_unit_id BIGINT REFERENCES administrative_units(id),
    target_location_id BIGINT REFERENCES wifi_locations(id),
    priority INT NOT NULL DEFAULT 1,
    start_time TIMESTAMP WITH TIME ZONE NOT NULL,
    end_time TIMESTAMP WITH TIME ZONE NOT NULL,
    status VARCHAR(50) NOT NULL DEFAULT 'DRAFT', -- DRAFT, PENDING_APPROVAL, APPROVED, REJECTED, EXPIRED
    created_by VARCHAR(100),
    approved_by VARCHAR(100),
    approved_at TIMESTAMP WITH TIME ZONE,
    reject_reason TEXT,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_campaigns_status ON campaigns(status);
CREATE INDEX idx_campaigns_timerange ON campaigns(start_time, end_time);

-- 3. Campaign Approval Audit Logs
CREATE TABLE campaign_approvals (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    campaign_id BIGINT NOT NULL REFERENCES campaigns(id),
    action VARCHAR(50) NOT NULL, -- SUBMIT, APPROVE, REJECT
    actor VARCHAR(100) NOT NULL,
    comment TEXT,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

-- 4. Smart Surveys Engine
CREATE TABLE surveys (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    campaign_id BIGINT REFERENCES campaigns(id),
    title VARCHAR(255) NOT NULL,
    description TEXT,
    max_responses_quota INT DEFAULT 1000,
    current_responses_count INT NOT NULL DEFAULT 0,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE survey_questions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    survey_id BIGINT NOT NULL REFERENCES surveys(id),
    question_text TEXT NOT NULL,
    question_type VARCHAR(50) NOT NULL, -- SINGLE_CHOICE, MULTI_CHOICE, TEXT, RATING
    options_json TEXT, -- JSON Array: ["Rất hài lòng", "Hài lòng", "Chưa hài lòng"]
    sort_order INT NOT NULL DEFAULT 0,
    required BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE survey_branching_rules (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    question_id BIGINT NOT NULL REFERENCES survey_questions(id),
    condition_value VARCHAR(255) NOT NULL,
    next_question_id BIGINT REFERENCES survey_questions(id),
    terminate_survey BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE survey_responses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    survey_id BIGINT NOT NULL REFERENCES surveys(id),
    location_id BIGINT REFERENCES wifi_locations(id),
    client_mac VARCHAR(50) NOT NULL,
    answers_json TEXT NOT NULL,
    submitted_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_survey_responses_survey_id ON survey_responses(survey_id);

-- 5. Remembered Devices for One-Click Re-login (Bypass OTP within 30 days)
CREATE TABLE remembered_devices (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_mac VARCHAR(50) NOT NULL UNIQUE,
    phone_number VARCHAR(50),
    remember_duration_days INT NOT NULL DEFAULT 30,
    bypass_otp_until TIMESTAMP WITH TIME ZONE NOT NULL,
    last_seen_at TIMESTAMP WITH TIME ZONE NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_remembered_devices_mac ON remembered_devices(client_mac);

