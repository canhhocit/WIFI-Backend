-- ==============================================================================
-- V1: Initial Database Schema for Wi-Fi Captive Portal Management System
-- Compatible with PostgreSQL 12+ and H2 (PostgreSQL Mode)
-- ==============================================================================

-- 1. Admin Users & Roles
CREATE TABLE admin_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(50) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    email VARCHAR(100) NOT NULL UNIQUE,
    full_name VARCHAR(100) NOT NULL,
    role VARCHAR(30) NOT NULL DEFAULT 'ROLE_ADMIN',
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);

-- 2. Wi-Fi Deployment Locations
CREATE TABLE wifi_locations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug VARCHAR(60) NOT NULL UNIQUE,
    name VARCHAR(100) NOT NULL,
    address VARCHAR(255),
    description VARCHAR(500),
    session_duration_minutes INT NOT NULL DEFAULT 120,
    max_bandwidth_mbps INT NOT NULL DEFAULT 20,
    terms_and_conditions TEXT NOT NULL,
    welcome_message VARCHAR(255) DEFAULT 'Welcome to High-Speed Wi-Fi',
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);

-- 3. Device Activity & Metadata
CREATE TABLE devices (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mac_address VARCHAR(17) NOT NULL UNIQUE,
    ip_address VARCHAR(45),
    hostname VARCHAR(100),
    user_agent TEXT,
    os_type VARCHAR(50),
    first_seen_at TIMESTAMP WITH TIME ZONE NOT NULL,
    last_seen_at TIMESTAMP WITH TIME ZONE NOT NULL,
    is_blocked BOOLEAN NOT NULL DEFAULT FALSE
);

-- 4. Guest Sessions
CREATE TABLE guest_sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_token VARCHAR(64) NOT NULL UNIQUE,
    location_id BIGINT NOT NULL REFERENCES wifi_locations(id),
    device_id BIGINT REFERENCES devices(id),
    mac_address VARCHAR(17) NOT NULL,
    ip_address VARCHAR(45) NOT NULL,
    guest_name VARCHAR(100),
    guest_contact VARCHAR(100),
    consent_given BOOLEAN NOT NULL DEFAULT TRUE,
    consent_timestamp TIMESTAMP WITH TIME ZONE NOT NULL,
    status VARCHAR(20) NOT NULL, -- PENDING, AUTHORIZED, REVOKED, EXPIRED, FAILED
    authorized_at TIMESTAMP WITH TIME ZONE,
    expires_at TIMESTAMP WITH TIME ZONE,
    revoked_at TIMESTAMP WITH TIME ZONE,
    revoked_by VARCHAR(50),
    revoke_reason VARCHAR(255),
    failure_reason VARCHAR(255),
    gateway_reference VARCHAR(100),
    bytes_downloaded BIGINT DEFAULT 0,
    bytes_uploaded BIGINT DEFAULT 0,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);

-- 5. Gateway Transactions & Audit Logs
CREATE TABLE gateway_transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id BIGINT REFERENCES guest_sessions(id),
    operation VARCHAR(20) NOT NULL, -- AUTHORIZE, REVOKE, STATUS_CHECK
    adapter_type VARCHAR(20) NOT NULL, -- MOCK, OPNSENSE
    is_simulated BOOLEAN NOT NULL DEFAULT TRUE,
    success BOOLEAN NOT NULL,
    status_code INT,
    error_message TEXT,
    raw_response TEXT,
    execution_time_ms BIGINT,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

-- 6. Audit Events
CREATE TABLE audit_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    action VARCHAR(50) NOT NULL,
    actor_username VARCHAR(50) NOT NULL,
    client_ip VARCHAR(45),
    target_type VARCHAR(50),
    target_id VARCHAR(100),
    details TEXT,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

-- Indexes for performance and frequent query patterns
CREATE INDEX idx_sessions_location_status ON guest_sessions (location_id, status);
CREATE INDEX idx_sessions_mac ON guest_sessions (mac_address);
CREATE INDEX idx_sessions_status_expires ON guest_sessions (status, expires_at);
CREATE INDEX idx_sessions_created_at ON guest_sessions (created_at DESC);
CREATE INDEX idx_audit_created_at ON audit_events (created_at DESC);
CREATE INDEX idx_devices_mac ON devices (mac_address);
CREATE INDEX idx_gateway_tx_session ON gateway_transactions (session_id);
