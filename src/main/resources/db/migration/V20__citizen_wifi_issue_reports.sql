-- ==============================================================================
-- V20: Citizen Wi-Fi Issue Reports and Automatic Incident Trigger
-- ==============================================================================

CREATE TABLE citizen_issue_reports (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    location_id BIGINT REFERENCES wifi_locations(id),
    client_mac VARCHAR(50),
    client_ip VARCHAR(50),
    phone_number VARCHAR(30),
    reporter_name VARCHAR(100),
    issue_type VARCHAR(50) NOT NULL, -- SLOW_CONNECTION, CANNOT_CONNECT, SIGNAL_WEAK, PORTAL_ERROR, POWER_OUTAGE, OTHER
    description TEXT,
    status VARCHAR(30) NOT NULL DEFAULT 'PENDING', -- PENDING, AGGREGATED_TO_INCIDENT, RESOLVED
    incident_ticket_id BIGINT REFERENCES incident_tickets(id),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_citizen_reports_location_time ON citizen_issue_reports(location_id, created_at);
CREATE INDEX idx_citizen_reports_status ON citizen_issue_reports(status);
CREATE INDEX idx_citizen_reports_incident ON citizen_issue_reports(incident_ticket_id);
