-- 1. Bảng Cây địa bàn 3 cấp (Administrative Units)
CREATE TABLE administrative_units (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_id BIGINT REFERENCES administrative_units(id),
    code VARCHAR(50) NOT NULL UNIQUE,
    name VARCHAR(100) NOT NULL,
    level INT NOT NULL, -- 1: Thành phố, 2: Quận/Huyện/Thị xã/Đặc khu, 3: Xã/Phường/Thị trấn
    path VARCHAR(255) NOT NULL, -- Ví dụ: /HP/, /HP/HP_HB/, /HP/HP_HB/HP_HB_P01/
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE', -- ACTIVE, INACTIVE, MERGED, SPLIT
    merged_to_id BIGINT REFERENCES administrative_units(id),
    notes VARCHAR(255),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_admin_units_parent ON administrative_units(parent_id);
CREATE INDEX idx_admin_units_level ON administrative_units(level);
CREATE INDEX idx_admin_units_path ON administrative_units(path);

-- 2. Mở rộng bảng wifi_locations phục vụ 1.584 Nhà văn hóa
ALTER TABLE wifi_locations ADD COLUMN IF NOT EXISTS admin_unit_id BIGINT REFERENCES administrative_units(id);
ALTER TABLE wifi_locations ADD COLUMN IF NOT EXISTS location_code VARCHAR(50);
ALTER TABLE wifi_locations ADD COLUMN IF NOT EXISTS latitude DOUBLE PRECISION;
ALTER TABLE wifi_locations ADD COLUMN IF NOT EXISTS longitude DOUBLE PRECISION;
ALTER TABLE wifi_locations ADD COLUMN IF NOT EXISTS status VARCHAR(20) DEFAULT 'ACTIVE'; -- ACTIVE, MAINTENANCE, SUSPENDED, INACTIVE
ALTER TABLE wifi_locations ADD COLUMN IF NOT EXISTS status_reason VARCHAR(255);
ALTER TABLE wifi_locations ADD COLUMN IF NOT EXISTS isp_name VARCHAR(50); -- VNPT, Viettel, FPT
ALTER TABLE wifi_locations ADD COLUMN IF NOT EXISTS circuit_code VARCHAR(100);
ALTER TABLE wifi_locations ADD COLUMN IF NOT EXISTS contact_name VARCHAR(100);
ALTER TABLE wifi_locations ADD COLUMN IF NOT EXISTS contact_phone VARCHAR(20);

CREATE INDEX idx_wifi_locations_admin_unit ON wifi_locations(admin_unit_id);
CREATE INDEX idx_wifi_locations_code ON wifi_locations(location_code);
CREATE INDEX idx_wifi_locations_status ON wifi_locations(status);

-- 3. Bảng Quản lý thiết bị mạng hạ tầng (ONT, Router, Access Point)
CREATE TABLE network_devices (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    location_id BIGINT REFERENCES wifi_locations(id),
    device_type VARCHAR(30) NOT NULL, -- ONT, ROUTER, ACCESS_POINT
    serial_number VARCHAR(100) NOT NULL UNIQUE,
    mac_address VARCHAR(17) NOT NULL UNIQUE,
    model VARCHAR(100),
    vendor VARCHAR(100), -- Cisco, Ruijie, Mikrotik, Huawei, VNPT Technology
    firmware_version VARCHAR(50),
    ip_address VARCHAR(45),
    status VARCHAR(20) NOT NULL DEFAULT 'ONLINE', -- ONLINE, OFFLINE, DEGRADED, MAINTENANCE
    cpu_usage_percent INT DEFAULT 0,
    memory_usage_percent INT DEFAULT 0,
    uptime_seconds BIGINT DEFAULT 0,
    last_seen_at TIMESTAMP WITH TIME ZONE,
    installed_at TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_network_devices_location ON network_devices(location_id);
CREATE INDEX idx_network_devices_status ON network_devices(status);
CREATE INDEX idx_network_devices_mac ON network_devices(mac_address);

-- 4. Bảng Nhật ký thay thế thiết bị hỏng tại hiện trường (Hardware Swap)
CREATE TABLE device_swap_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    location_id BIGINT NOT NULL REFERENCES wifi_locations(id),
    old_device_id BIGINT REFERENCES network_devices(id),
    new_device_id BIGINT NOT NULL REFERENCES network_devices(id),
    old_serial_number VARCHAR(100),
    new_serial_number VARCHAR(100) NOT NULL,
    old_mac_address VARCHAR(17),
    new_mac_address VARCHAR(17) NOT NULL,
    swap_reason VARCHAR(255) NOT NULL,
    swapped_by VARCHAR(50) NOT NULL,
    swapped_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_device_swap_logs_location ON device_swap_logs(location_id);

